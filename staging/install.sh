#!/usr/bin/env bash
# Install or update the PickleMyPaddle staging stack on home-server (SCRUM-16).
#
#   sudo ./staging/install.sh              install, or apply changes from this checkout
#   sudo ./staging/install.sh --check      only run the pre-flight checks
#   sudo ./staging/install.sh --set-token  store (or replace) the GitHub token used
#                                          to post "staging" commit statuses (SCRUM-17)
#   sudo ./staging/install.sh --tailscale  also serve staging over Tailscale (HTTPS, tailnet
#                                          only) at https://<host>.<tailnet>.ts.net:8443 (SCRUM-38)
#   sudo ./staging/install.sh --tailscale-off  stop serving it over Tailscale
#   sudo ./staging/install.sh --set-editor-app  store (or replace) the blog editor's GitHub App
#                                          client ID and secret (SCRUM-34)
#   sudo ./staging/install.sh --set-admin-logins  set the Tailscale login(s) allowed into the order
#                                          admin (SCRUM-71/72)
#
# Safe to re-run: it keeps your existing /opt/picklemypaddle/staging/.env.
# You run this by hand after reviewing a change; nothing runs it automatically.
set -euo pipefail

SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEST_DIR="/opt/picklemypaddle/staging"
UNIT_DIR="/etc/systemd/system"
TOKEN_FILE="/etc/picklemypaddle/github-status.token"
STATUS_REPO="thehunfromoz/picklemypaddle-site"
SECRETS_FILE="/etc/picklemypaddle/integrations.env"
EDITOR_SECRETS_FILE="/etc/picklemypaddle/editor.env"
# SCRUM-64: the order database's password. integrations gets the matching DATABASE_URL.
POSTGRES_SECRETS_FILE="/etc/picklemypaddle/postgres.env"
PGDATA_VOLUME="pmp-staging-pgdata"
IMAGES=(ghcr.io/thehunfromoz/picklemypaddle-site:staging ghcr.io/thehunfromoz/picklemypaddle-integrations:staging
  ghcr.io/thehunfromoz/picklemypaddle-site-editor:staging)
CHECK_ONLY=false
SET_TOKEN=false
SET_EDITOR_APP=false
SET_ADMIN_LOGINS=false
case "${1:-}" in
  --check) CHECK_ONLY=true ;;
  --set-token) SET_TOKEN=true ;;
  --set-editor-app) SET_EDITOR_APP=true ;;
  --set-admin-logins) SET_ADMIN_LOGINS=true ;;
  --tailscale) exec "$SRC_DIR/tailscale.sh" on ;;
  --tailscale-off) exec "$SRC_DIR/tailscale.sh" off ;;
  "") ;;
  *) echo "usage: sudo $0 [--check|--set-token|--set-editor-app|--set-admin-logins|--tailscale|--tailscale-off]" >&2; exit 2 ;;
esac

ok() { printf '  \033[32m✓\033[0m %s\n' "$*"; }
fail() { printf '  \033[31m✗\033[0m %s\n' "$*" >&2; exit 1; }
info() { printf '\n%s\n' "$*"; }

[[ $EUID -eq 0 ]] || fail "run with sudo"

# Ask GitHub whether a token can see the repo it will post statuses to.
token_works() { # token_works <file>
  printf 'header = "Authorization: Bearer %s"\n' "$(tr -d '[:space:]' <"$1")" |
    curl -fsS --config - --max-time 15 -o /dev/null \
      -H "Accept: application/vnd.github+json" "https://api.github.com/repos/$STATUS_REPO"
}

if $SET_TOKEN; then
  info "GitHub status token (fine-grained, only '$STATUS_REPO', only 'Commit statuses: Read and write')"
  read -rsp "  Paste the token (input hidden): " token
  echo
  [[ "$token" == github_pat_* ]] || fail "that doesn't look like a fine-grained token (should start with github_pat_)"
  install -d -m 0700 "$(dirname "$TOKEN_FILE")"
  tmp="$(mktemp "$(dirname "$TOKEN_FILE")/.token.XXXXXX")"
  printf '%s\n' "$token" >"$tmp"
  unset token
  chmod 0600 "$tmp"
  token_works "$tmp" || { rm -f "$tmp"; fail "GitHub rejected the token, or it can't see $STATUS_REPO"; }
  mv "$tmp" "$TOKEN_FILE"
  ok "token saved to $TOKEN_FILE (root-only) and accepted by GitHub"
  exit 0
fi

# The blog editor's secrets file (SCRUM-34): the GitHub App's client ID and secret (set with
# --set-editor-app) and KEYSTATIC_SECRET, a random key for the editor's sign-in cookies,
# generated here once. Root-only, like the integrations file.
new_editor_secrets() {
  ( umask 077; cat >"$EDITOR_SECRETS_FILE" <<SECRETS
# PickleMyPaddle blog editor (Keystatic): STAGING secrets. Root-only (chmod 600).
# Set the GitHub App values with: sudo ./staging/install.sh --set-editor-app
# KEYSTATIC_SECRET signs the editor's sign-in cookies; generated by install.sh.
KEYSTATIC_GITHUB_CLIENT_ID=
KEYSTATIC_GITHUB_CLIENT_SECRET=
KEYSTATIC_SECRET=$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')
SECRETS
  )
}
editor_set() { secret_set "$EDITOR_SECRETS_FILE" "$1" "$2"; }
secret_set() { # secret_set <file> <key> <value>: replace one line, keeping the rest (root-only)
  python3 - "$1" "$2" "$3" <<'PY2'
import os, sys
path, key, value = sys.argv[1:]
lines = open(path, encoding="utf-8").read().splitlines()
out, done = [], False
for line in lines:
    if line.startswith(key + "="):
        if not done:
            out.append(f"{key}={value}")
            done = True
        continue
    out.append(line)
if not done:
    out.append(f"{key}={value}")
tmp = path + ".tmp"
fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
with os.fdopen(fd, "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
os.replace(tmp, path)
PY2
}

if $SET_EDITOR_APP; then
  info "Blog editor GitHub App (GitHub → Settings → Developer settings → GitHub Apps → the editor app)"
  read -rp "  Client ID: " client_id
  [[ "$client_id" =~ ^Iv[0-9A-Za-z.]+$ ]] || fail "that doesn't look like a GitHub App client ID (it starts with Iv)"
  read -rsp "  Client secret (input hidden): " client_secret
  echo
  [[ "$client_secret" =~ ^[0-9a-f]{40}$ ]] || fail "that doesn't look like a GitHub App client secret (40 hex characters)"
  install -d -m 0700 "$(dirname "$EDITOR_SECRETS_FILE")"
  [[ -f "$EDITOR_SECRETS_FILE" ]] || new_editor_secrets
  editor_set KEYSTATIC_GITHUB_CLIENT_ID "$client_id"
  editor_set KEYSTATIC_GITHUB_CLIENT_SECRET "$client_secret"
  unset client_secret
  chown root:root "$EDITOR_SECRETS_FILE"; chmod 600 "$EDITOR_SECRETS_FILE"
  ok "saved to $EDITOR_SECRETS_FILE (root-only)"
  if [[ -f "$DEST_DIR/compose.staging.yml" ]]; then
    docker compose --project-directory "$DEST_DIR" -f "$DEST_DIR/compose.staging.yml" \
      up -d --pull never --no-deps --force-recreate --wait --wait-timeout 60 editor >/dev/null ||
      fail "the editor didn't come back healthy; see: sudo docker compose -p pmp-staging logs editor"
    port="$(sed -n 's/^EDITOR_LOCAL_PORT=//p' "$DEST_DIR/.env" | tail -n1)"
    login="$(curl -s -o /dev/null -D - "http://127.0.0.1:${port:-8101}/api/keystatic/github/login" || true)"
    if grep -qi "^location: https://github.com/login/oauth/authorize?client_id=$client_id&" <<<"$login"; then
      ok "editor restarted and sends sign-in to GitHub with this app"
    else
      fail "editor restarted, but sign-in doesn't use this app yet; check: sudo docker compose -p pmp-staging logs editor"
    fi
  else
    ok "staging isn't installed yet; the editor picks these up on install"
  fi
  exit 0
fi

# SCRUM-71/72: who may sign in to the order admin. Their Tailscale login(s), as Tailscale Serve sends
# them in Tailscale-User-Login (admin console → Users; e.g. you@example.com or you@github). Kept in
# the root-only integrations secrets file beside EMAIL_ALLOWLIST: personal data, not for the repo.
if $SET_ADMIN_LOGINS; then
  [[ -f "$SECRETS_FILE" ]] || fail "staging isn't installed yet; run: sudo $0"
  info "Order admin: Tailscale login(s) allowed in (Tailscale admin console → Users, the login under each name)"
  read -rp "  Login(s), comma-separated: " logins
  logins="$(tr -d '[:space:]' <<<"$logins" | tr '[:upper:]' '[:lower:]')"
  [[ "$logins" =~ ^[^@,]+@[^@,]+(,[^@,]+@[^@,]+)*$ ]] || fail "that doesn't look like Tailscale logins (name@domain, comma-separated)"
  secret_set "$SECRETS_FILE" ADMIN_LOGINS "$logins"
  chown root:root "$SECRETS_FILE"; chmod 600 "$SECRETS_FILE"
  ok "saved to $SECRETS_FILE (root-only)"
  if [[ -f "$DEST_DIR/compose.staging.yml" ]]; then
    docker compose --project-directory "$DEST_DIR" -f "$DEST_DIR/compose.staging.yml" \
      up -d --pull never --no-deps --force-recreate integrations >/dev/null ||
      fail "integrations didn't restart; see: sudo docker compose -p pmp-staging logs integrations"
    port="$(sed -n 's/^ADMIN_LOCAL_PORT=//p' "$DEST_DIR/.env" | tail -n1)"
    first="${logins%%,*}"
    for _ in $(seq 1 30); do
      code="$(curl -s -o /dev/null -w '%{http_code}' -H "Tailscale-User-Login: $first" "http://127.0.0.1:${port:-8100}/admin/orders" || true)"
      [[ "$code" == 200 ]] && break
      sleep 2
    done
    if [[ "$code" == 200 ]]; then
      ok "integrations restarted; the admin lets $first in (open it over Tailscale: sudo $0 --tailscale)"
    else
      fail "integrations restarted, but the admin answered $code for $first; check: sudo docker compose -p pmp-staging logs integrations"
    fi
  fi
  exit 0
fi

info "Pre-flight checks"
command -v docker >/dev/null || fail "Docker is not installed"
docker info >/dev/null 2>&1 || fail "Docker daemon is not running"
docker compose version >/dev/null 2>&1 || fail "Docker Compose v2 plugin missing (apt install docker-compose-plugin)"
ok "Docker $(docker version -f '{{.Server.Version}}'), $(docker compose version --short | sed 's/^/Compose /')"
command -v python3 >/dev/null || fail "python3 missing (apt install python3)"
command -v flock >/dev/null || fail "flock missing (apt install util-linux)"
ok "python3 and flock present"
command -v curl >/dev/null || fail "curl missing (apt install curl)"
command -v timeout >/dev/null || fail "timeout missing (apt install coreutils)"

# Port: read from the installed .env if present, else the example.
ENV_FILE="$DEST_DIR/.env"
[[ -f "$ENV_FILE" ]] || ENV_FILE="$SRC_DIR/.env.example"
PORT="$(sed -n 's/^STAGING_PORT=//p' "$ENV_FILE" | tail -n1)"
PORT="${PORT:-8088}"
ours="$(docker ps --filter label=com.docker.compose.project=pmp-staging \
  --filter label=com.docker.compose.service=gateway -q)"
if ss -ltnH "sport = :$PORT" | grep -q .; then
  if [[ -n "$ours" ]]; then
    ok "port $PORT is in use by the staging gateway itself (re-install)"
  else
    ss -ltnpH "sport = :$PORT" >&2 || true
    fail "port $PORT is already used by something else; set STAGING_PORT in $ENV_FILE"
  fi
else
  ok "port $PORT is free"
fi

# The loopback-only listeners for Tailscale Serve: the blog editor (SCRUM-34) and the order admin
# (SCRUM-71). Checked before anything changes: a port another program or container holds would
# stop the gateway starting, and staging with it (29 Oct 2026: wanderer already had 8090).
setting() { # setting <key> <default>
  local v; v="$(sed -n "s/^$1=//p" "$ENV_FILE" | tail -n1)"; echo "${v:-$2}"
}
loopback_port_free() { # loopback_port_free <port> <setting> <gateway container port> <what>
  local port="$1" key="$2" cport="$3" what="$4" others
  if [[ -n "$ours" ]] && docker port "$ours" "$cport/tcp" 2>/dev/null | grep -q ":$port\$"; then
    ok "port $port ($what) is the staging gateway's own"
    return
  fi
  others="$(docker ps --format '{{.Names}} {{.Ports}}' | grep -E "[:]$port->" | grep -v '^pmp-staging-gateway-' || true)"
  if [[ -n "$others" ]] || ss -ltnH "sport = :$port" | grep -q .; then
    [[ -z "$others" ]] || printf '    %s\n' "$others" >&2
    ss -ltnpH "sport = :$port" >&2 || true
    fail "port $port ($what) is already used by something else (above). Pick a free one: set $key=<port> in $DEST_DIR/.env (find free ones with: sudo ss -ltn), then re-run. Nothing was changed."
  fi
  ok "port $port ($what) is free"
}
ED_LOCAL="$(setting EDITOR_LOCAL_PORT 8101)"
AD_LOCAL="$(setting ADMIN_LOCAL_PORT 8100)"
[[ "$ED_LOCAL" != "$AD_LOCAL" && "$ED_LOCAL" != "$PORT" && "$AD_LOCAL" != "$PORT" ]] ||
  fail "STAGING_PORT ($PORT), EDITOR_LOCAL_PORT ($ED_LOCAL) and ADMIN_LOCAL_PORT ($AD_LOCAL) must all differ; fix $DEST_DIR/.env"
loopback_port_free "$ED_LOCAL" EDITOR_LOCAL_PORT 8081 "blog editor, loopback"
loopback_port_free "$AD_LOCAL" ADMIN_LOCAL_PORT 8082 "order admin, loopback"

for img in "${IMAGES[@]}"; do
  if docker pull -q "$img" >/dev/null 2>&1; then
    ok "can pull ${img#ghcr.io/thehunfromoz/}"
  else
    fail "cannot pull $img (no internet, or the package isn't public yet; see the runbook)"
  fi
done

if [[ -f "$SECRETS_FILE" ]]; then
  perms="$(stat -c '%a %U' "$SECRETS_FILE")"
  if [[ "$perms" == "600 root" ]]; then ok "integrations secrets file is root-only"; else
    fail "$SECRETS_FILE must be owned by root with mode 600 (is: $perms); fix: sudo chmod 600 $SECRETS_FILE && sudo chown root:root $SECRETS_FILE"; fi
  if ! grep -q '^ADMIN_LOGINS=.\+' "$SECRETS_FILE"; then
    printf '  \033[33m!\033[0m no one may sign in to the order admin yet (it answers 503).\n    Add your Tailscale login with: sudo %s --set-admin-logins\n' "$0"
  fi
else
  printf '  \033[33m!\033[0m %s will be created (empty; add TEST-mode keys later, see runbook)\n' "$SECRETS_FILE"
fi

if [[ -f "$POSTGRES_SECRETS_FILE" ]]; then
  perms="$(stat -c '%a %U' "$POSTGRES_SECRETS_FILE")"
  if [[ "$perms" == "600 root" ]]; then ok "database password file is root-only"; else
    fail "$POSTGRES_SECRETS_FILE must be owned by root with mode 600 (is: $perms); fix: sudo chmod 600 $POSTGRES_SECRETS_FILE && sudo chown root:root $POSTGRES_SECRETS_FILE"; fi
elif docker volume inspect "$PGDATA_VOLUME" >/dev/null 2>&1; then
  fail "the database volume $PGDATA_VOLUME exists but $POSTGRES_SECRETS_FILE is missing: a new password wouldn't open it. Restore the file, or reset staging's database (runbook: 'Order database')"
else
  printf '  \033[33m!\033[0m %s will be created (random database password; DATABASE_URL added to %s)\n' "$POSTGRES_SECRETS_FILE" "$SECRETS_FILE"
fi

if [[ -f "$EDITOR_SECRETS_FILE" ]]; then
  perms="$(stat -c '%a %U' "$EDITOR_SECRETS_FILE")"
  if [[ "$perms" == "600 root" ]]; then ok "blog editor secrets file is root-only"; else
    fail "$EDITOR_SECRETS_FILE must be owned by root with mode 600 (is: $perms); fix: sudo chmod 600 $EDITOR_SECRETS_FILE && sudo chown root:root $EDITOR_SECRETS_FILE"; fi
  if ! grep -q '^KEYSTATIC_GITHUB_CLIENT_ID=Iv' "$EDITOR_SECRETS_FILE"; then
    printf '  \033[33m!\033[0m the blog editor has no GitHub App yet: it runs, but sign-in fails.\n    Add it with: sudo %s --set-editor-app (see runbook)\n' "$0"
  fi
else
  printf '  \033[33m!\033[0m %s will be created (sign-in key generated; add the GitHub App with --set-editor-app)\n' "$EDITOR_SECRETS_FILE"
fi

if [[ -r "$TOKEN_FILE" ]]; then
  if token_works "$TOKEN_FILE"; then ok "GitHub status token works"; else
    printf '  \033[33m!\033[0m GitHub status token is rejected (expired?). Replace it: sudo %s --set-token\n' "$0"; fi
else
  printf '  \033[33m!\033[0m no GitHub status token yet: staging works, but results won'"'"'t show on GitHub.\n    Add one with: sudo %s --set-token (see runbook)\n' "$0"
fi

# Is what's installed in /opt the same as this checkout? (The timer runs /opt.)
stale=""
for f in compose.staging.yml gateway/Caddyfile update.sh backup.sh; do
  cmp -s "$SRC_DIR/$f" "$DEST_DIR/$f" 2>/dev/null || stale="$stale $f"
done
for f in pmp-staging-update.service pmp-staging-update.timer pmp-staging-backup.service pmp-staging-backup.timer; do
  cmp -s "$SRC_DIR/systemd/$f" "$UNIT_DIR/$f" 2>/dev/null || stale="$stale $f"
done
if [[ -n "$stale" ]]; then
  printf '  \033[33m!\033[0m installed files differ from this checkout:%s\n    Apply them with: sudo %s\n' "$stale" "$0"
else
  ok "installed files match this checkout"
fi

$CHECK_ONLY && { info "Checks passed. Nothing installed (--check)."; exit 0; }

info "Installing to $DEST_DIR"
install -d -m 0755 "$DEST_DIR" "$DEST_DIR/gateway"
install -d -m 0700 "$(dirname "$SECRETS_FILE")"
if [[ ! -f "$SECRETS_FILE" ]]; then
  ( umask 077; cat >"$SECRETS_FILE" <<'SECRETS'
# PickleMyPaddle integrations service: STAGING secrets. Root-only (chmod 600).
# TEST-MODE values only: the service refuses a live Stripe key on staging.
# Leave a value empty until its integration is built. After editing, apply with:
#   cd ~/picklemypaddle-infra && sudo ./staging/install.sh
# APP_ENV, PORT and PUBLIC_SITE_ORIGIN are set in compose.staging.yml, not here.
# DATABASE_URL is written by install.sh from /etc/picklemypaddle/postgres.env (SCRUM-64).
STRIPE_SECRET_KEY=
STRIPE_WEBHOOK_SECRET=
HUBSPOT_ACCESS_TOKEN=
HUBSPOT_PORTAL_ID=
SECRETS
  )
  ok "created $SECRETS_FILE (root-only, empty)"
else
  chmod 600 "$SECRETS_FILE"; chown root:root "$SECRETS_FILE"
  ok "kept $SECRETS_FILE (root-only)"
fi
# SCRUM-64: the database password, made once. Never replaced: the database volume only opens with it.
if [[ ! -f "$POSTGRES_SECRETS_FILE" ]]; then
  ( umask 077; cat >"$POSTGRES_SECRETS_FILE" <<SECRETS
# PickleMyPaddle order database (Postgres): STAGING password. Root-only (chmod 600).
# Made by install.sh. Don't change it: the database volume was initialised with it.
# integrations reaches the database with the matching DATABASE_URL in $SECRETS_FILE.
POSTGRES_PASSWORD=$(head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n')
SECRETS
  )
  ok "created $POSTGRES_SECRETS_FILE (root-only, random password)"
else
  chmod 600 "$POSTGRES_SECRETS_FILE"; chown root:root "$POSTGRES_SECRETS_FILE"
  ok "kept $POSTGRES_SECRETS_FILE (root-only)"
fi
db_password="$(sed -n 's/^POSTGRES_PASSWORD=//p' "$POSTGRES_SECRETS_FILE" | tail -n1)"
[[ "$db_password" =~ ^[0-9a-f]{32,}$ ]] || fail "$POSTGRES_SECRETS_FILE has no usable POSTGRES_PASSWORD (expected the hex password install.sh makes)"
if grep -qxF "DATABASE_URL=postgres://pmp:${db_password}@postgres:5432/pmp" "$SECRETS_FILE"; then
  ok "integrations already has the database's DATABASE_URL"
else
  secret_set "$SECRETS_FILE" DATABASE_URL "postgres://pmp:${db_password}@postgres:5432/pmp"
  chown root:root "$SECRETS_FILE"; chmod 600 "$SECRETS_FILE"
  ok "wrote DATABASE_URL to $SECRETS_FILE"
fi
unset db_password

if [[ ! -f "$EDITOR_SECRETS_FILE" ]]; then
  new_editor_secrets
  ok "created $EDITOR_SECRETS_FILE (root-only, sign-in key generated)"
else
  chmod 600 "$EDITOR_SECRETS_FILE"; chown root:root "$EDITOR_SECRETS_FILE"
  ok "kept $EDITOR_SECRETS_FILE (root-only)"
fi
install -m 0644 "$SRC_DIR/compose.staging.yml" "$DEST_DIR/compose.staging.yml"
install -m 0644 "$SRC_DIR/gateway/Caddyfile" "$DEST_DIR/gateway/Caddyfile"
install -m 0755 "$SRC_DIR/update.sh" "$DEST_DIR/update.sh"
install -m 0755 "$SRC_DIR/backup.sh" "$DEST_DIR/backup.sh"
if [[ -f "$DEST_DIR/.env" ]]; then
  ok "kept existing .env"
  # Settings added since it was created (SCRUM-34 adds the editor's): append any that are missing,
  # with their .env.example value, so an existing install picks up new services.
  added=""
  while IFS='=' read -r key value; do
    [[ "$key" =~ ^[A-Z_]+$ ]] || continue
    grep -q "^$key=" "$DEST_DIR/.env" || { printf '%s=%s\n' "$key" "$value" >>"$DEST_DIR/.env"; added="$added $key"; }
  done <"$SRC_DIR/.env.example"
  [[ -z "$added" ]] || ok "added new settings to .env:$added"
else
  install -m 0644 "$SRC_DIR/.env.example" "$DEST_DIR/.env"
  ok "created .env from .env.example"
fi
docker compose --project-directory "$DEST_DIR" -f "$DEST_DIR/compose.staging.yml" config -q
ok "compose file is valid"

info "Installing the updater (systemd timer, every 2 minutes)"
install -m 0644 "$SRC_DIR/systemd/pmp-staging-update.service" "$UNIT_DIR/"
install -m 0644 "$SRC_DIR/systemd/pmp-staging-update.timer" "$UNIT_DIR/"
install -m 0644 "$SRC_DIR/systemd/pmp-staging-backup.service" "$UNIT_DIR/"
install -m 0644 "$SRC_DIR/systemd/pmp-staging-backup.timer" "$UNIT_DIR/"
systemctl daemon-reload
systemctl enable --now pmp-staging-update.timer >/dev/null
ok "timer enabled"
systemctl enable --now pmp-staging-backup.timer >/dev/null
ok "nightly backup enabled (02:30 Sydney time, kept $(sed -n 's/^BACKUP_KEEP_DAYS=//p' "$DEST_DIR/.env" | tail -n1 || true) days; SCRUM-64)"

# Refresh the gateway BEFORE the first update: the update runs the smoke tests
# through the gateway, and a running gateway keeps its old Caddyfile until it is
# recreated (SCRUM-38: new staging checks ran against the old config and failed).
# On a first install there is no gateway yet; the updater starts it.
if [[ -n "$ours" ]]; then
  info "Refreshing the gateway (new image and config)"
  docker compose --project-directory "$DEST_DIR" -f "$DEST_DIR/compose.staging.yml" pull -q gateway || true
  docker compose --project-directory "$DEST_DIR" -f "$DEST_DIR/compose.staging.yml" \
    up -d --pull never --force-recreate --no-deps --wait --wait-timeout 60 gateway >/dev/null ||
    fail "the gateway didn't come back healthy; see: sudo docker compose -p pmp-staging logs gateway"
  if curl -fsS "http://127.0.0.1:$PORT/env.css" | grep -q 'data-env="staging-only"'; then
    ok "gateway restarted with this checkout's config and serves the staging /env.css"
  else
    fail "gateway restarted, but /env.css isn't the staging one; check: curl http://127.0.0.1:$PORT/env.css"
  fi
fi

info "First update (pulls images, starts the stack, waits for health checks)"
if systemctl start pmp-staging-update.service; then
  ok "staging is up"
else
  journalctl -u pmp-staging-update.service -n 30 --no-pager >&2
  fail "first update failed; see the log above"
fi

# Restart integrations and the editor if their settings (secrets files) changed; no-op otherwise.
docker compose --project-directory "$DEST_DIR" -f "$DEST_DIR/compose.staging.yml" \
  up -d --pull never --no-deps integrations editor >/dev/null 2>&1 || true

sleep 2

if curl -fsS "http://127.0.0.1:$PORT/healthz" >/dev/null; then
  ok "http://127.0.0.1:$PORT/healthz answers"
else
  fail "the site didn't answer on port $PORT"
fi

# SCRUM-64: once integrations reports its database (images from SCRUM-65 on), it must be reachable.
api_status="$(curl -fsS "http://127.0.0.1:$PORT/api/status" 2>/dev/null || true)"
if grep -q '"database"' <<<"$api_status"; then
  if grep -q '"reachable":true' <<<"$api_status"; then
    ok "integrations reaches the order database ($(grep -o '"migration":[0-9]*' <<<"$api_status"))"
  else
    fail "integrations can't reach the order database; see: sudo docker compose -p pmp-staging logs integrations postgres"
  fi
fi

EDITOR_PORT="$(sed -n 's/^EDITOR_LOCAL_PORT=//p' "$DEST_DIR/.env" | tail -n1)"
EDITOR_PORT="${EDITOR_PORT:-8101}"
if curl -fsS -o /dev/null "http://127.0.0.1:$EDITOR_PORT/keystatic"; then
  ok "blog editor answers on 127.0.0.1:$EDITOR_PORT (Tailscale only: sudo $0 --tailscale)"
else
  printf '  \033[33m!\033[0m blog editor not answering yet on 127.0.0.1:%s; check: sudo docker compose -p pmp-staging ps editor\n' "$EDITOR_PORT"
fi
if [[ "$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$PORT/keystatic")" == 404 ]]; then
  ok "the LAN address doesn't serve the blog editor"
else
  fail "http://127.0.0.1:$PORT/keystatic should be 404 (the editor is Tailscale-only); re-run: sudo $0"
fi

# SCRUM-71: the order admin is on its own loopback-only listener, never on the LAN one.
if [[ "$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$PORT/admin/orders")" == 404 ]]; then
  ok "the LAN address doesn't serve the order admin"
else
  fail "http://127.0.0.1:$PORT/admin/orders should be 404 (the admin is Tailscale-only); re-run: sudo $0"
fi
ADMIN_PORT="$(sed -n 's/^ADMIN_LOCAL_PORT=//p' "$DEST_DIR/.env" | tail -n1)"
ADMIN_PORT="${ADMIN_PORT:-8100}"
case "$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$ADMIN_PORT/admin/orders")" in
  403) ok "order admin answers on 127.0.0.1:$ADMIN_PORT and refuses requests without a Tailscale login (Tailscale only: sudo $0 --tailscale)" ;;
  503) ok "order admin answers on 127.0.0.1:$ADMIN_PORT; no one may sign in yet: sudo $0 --set-admin-logins" ;;
  502) printf '  \033[33m!\033[0m the admin listener is up, but the integrations image predates SCRUM-71; it picks this up after its next update\n' ;;
  *) fail "the order admin isn't answering on 127.0.0.1:$ADMIN_PORT; check: sudo docker compose -p pmp-staging logs gateway integrations" ;;
esac

info "Done. Open http://home-server:$PORT from your Mac (runbook: runbooks/staging-home-server.md)."
